#!/usr/bin/env python3
"""Generate docs/architecture/modules.md from the real import graph.

Reads every module under ``src/lumos`` with :mod:`ast` (nothing is imported or
executed), aggregates module imports to the package that owns them, and writes
one Mermaid flowchart plus a table of the module-level edges it folded together.
Standard library only; no runtime dependency.

    python3 scripts/gen_modules.py            # rewrite docs/architecture/modules.md
    python3 scripts/gen_modules.py --check    # exit 1 if the committed file is stale
"""

from __future__ import annotations

import argparse
import ast
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
PACKAGE = "lumos"
COMPONENTS = (
    "lumos.core.nmap",
    "lumos.core",
    "lumos.services",
    "lumos.tui",
    "lumos.plugins",
    "lumos.cli",
    "lumos",
)


def _module_name(path: Path) -> str:
    relative = path.relative_to(SRC).with_suffix("")
    parts = list(relative.parts)
    if parts[-1] == "__init__":
        parts.pop()
    return ".".join(parts)


def _component(module: str) -> str:
    for candidate in COMPONENTS:
        if module == candidate:
            return candidate
        if candidate != "lumos" and module.startswith(candidate + "."):
            return candidate
    return "lumos"


def _resolve_relative(module: str, level: int, target: str | None) -> str:
    """Resolve ``from ..x import y`` against the importing module's package."""
    parts = module.split(".")
    package_parts = parts[:-1]  # drop the module leaf
    if level > 1:
        package_parts = package_parts[: -(level - 1)]
    base = ".".join(package_parts)
    return f"{base}.{target}" if target else base


def collect() -> tuple[Counter, list[tuple[str, str, str]]]:
    modules = {
        _module_name(path): path for path in sorted(SRC.joinpath(PACKAGE).rglob("*.py"))
    }
    known = set(modules) | {name for name in COMPONENTS}
    edges: Counter = Counter()
    detail: list[tuple[str, str, str]] = []
    for module, path in modules.items():
        tree = ast.parse(path.read_text(encoding="utf-8"))
        for node in ast.walk(tree):
            targets: list[str] = []
            if isinstance(node, ast.Import):
                targets = [alias.name for alias in node.names]
            elif isinstance(node, ast.ImportFrom):
                base = (
                    _resolve_relative(module, node.level, node.module)
                    if node.level
                    else (node.module or "")
                )
                targets = [base] if base in known else []
                if base and node.names:
                    for alias in node.names:
                        candidate = f"{base}.{alias.name}"
                        if candidate in modules:
                            targets.append(candidate)
            for target in targets:
                if not target.startswith(PACKAGE + "."):
                    continue
                if target == module:
                    continue
                source_component, target_component = _component(module), _component(target)
                if source_component == target_component:
                    continue
                edges[(source_component, target_component)] += 1
                detail.append((module, target, source_component))
    return edges, detail


def render(edges: Counter, detail: list[tuple[str, str, str]]) -> str:
    components = sorted({name for edge in edges for name in edge})
    lines = [
        "# Module imports",
        "",
        "Shows which packages import which, aggregated from the `ast` import graph "
        "of every file under `src/lumos`.",
        "Leaves out individual module edges, the direction of each call, and any "
        "import that stays inside one package; the table below lists every "
        "cross-package module edge.",
        "Generated by `scripts/gen_modules.py`; do not edit by hand.",
        "",
        "```mermaid",
        "flowchart LR",
    ]
    for index, name in enumerate(components):
        lines.append(f'    P{index}["{name}"]')
    for (source, target), count in sorted(edges.items()):
        left = components.index(source)
        right = components.index(target)
        lines.append(f"    P{left} -->|\"{count} imports\"| P{right}")
    lines.extend(
        [
            "```",
            "",
            "| importing module | imported module |",
            "| --- | --- |",
        ]
    )
    for module, target, _component_name in sorted(set(detail)):
        lines.append(f"| `{module}` | `{target}` |")
    lines.append("")
    return "\n".join(lines)


def generate(target: Path) -> Path:
    edges, detail = collect()
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render(edges, detail), encoding="utf-8")
    return target


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out",
        type=Path,
        default=ROOT / "docs" / "architecture" / "modules.md",
        help="file to write",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit 1 when the committed file differs from the generated one",
    )
    args = parser.parse_args(argv)
    if not args.check:
        print(generate(args.out))
        return 0
    edges, detail = collect()
    expected = render(edges, detail)
    if not args.out.exists() or args.out.read_text(encoding="utf-8") != expected:
        print(f"stale generated diagram: {args.out}", file=sys.stderr)
        return 1
    print("generated diagram is current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
